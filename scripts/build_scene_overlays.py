#!/usr/bin/env python3
"""Deterministic scene-overlay generator for the animated people (all nine studies + hero).

    python3 scripts/build_scene_overlays.py --write   # regenerate the managed overlay blocks in index.html
    python3 scripts/build_scene_overlays.py --check   # exit 1 unless index.html holds exactly the generated bytes

Input (shared contract, owned by the render workflow): assets/people/scenes.json plus, per actor, a rendered RGBA
strip under assets/people/scenes/<name>.png and its measured metadata <name>.json. This script owns the markup only:
for every scene it emits one static, decorative inline <svg class="scene-overlay"> in the SOURCE IMAGE pixel space
(viewBox 0 0 width height) and places it between its own markers inside the gallery link (xMidYMid meet, the image
is shown at its natural aspect) and, for study-1, inside .hero-image-stage (xMidYMid slice, matching object-fit:cover).

Per actor the overlay holds a nested <svg> frame viewport (one frame_width x frame_height frame of the strip, scaled
so the measured visible_body_height equals body_height source pixels and anchored at position by its feet or seat),
the clipped strip <image>, a ground shadow under the foot anchor and, optionally, a clipPath (visible_path, evenodd,
source coordinates) applied OUTSIDE the animated group so foreground occluders stay fixed. All animation values are
custom properties on the actor group (--frames, --rest, --tx, --ty, --scene-seconds, --move-seconds); styles.css plays
the single 4.4 s sequence once when app.js adds .scene-active, and the base transforms (no JS, reduced motion) rest on
the LAST frame at the END position. Nothing here is edited by hand; the FLOOR_PLAN block is never touched.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "assets" / "people" / "scenes.json"
INDEX_PATH = ROOT / "index.html"
STRIP_DIR = "assets/people/scenes/"
PERSONS = ("Nathan", "Carla")
FILTERS = ("none", "grayscale(1)")
SCENE_KEYS = {"id", "source", "width", "height", "source_sha256", "description", "actors"}
ACTOR_KEYS = {"id", "person", "strip", "metadata", "position", "anchor", "body_height", "travel", "move_until",
              "shadow", "opacity", "filter", "visible_path", "motion_note", "duration", "delay"}
META_KEYS = ("file", "frame_width", "frame_height", "frame_count", "strip_width", "strip_height",
             "visible_body_height", "foot_anchor", "body", "frames", "sha256", "person")
SHADOW_KEYS = {"rx", "ry", "opacity", "rotate"}
PATH_CHARS = re.compile(r"^[MmLlHhVvZzCcSsQqTtAa0-9 .,\-]+$")
SLUG = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
HERO_STAGE = '<div class="hero-image-stage">'
LEGACY_COMMENT = "<!-- Decorative overlay in the raster's own"
LEGACY_SVG = '<svg class="hero-walkers"'


class SceneError(Exception):
    """Any contract violation. Nothing is written when one is raised."""


def fail(message: str) -> None:
    raise SceneError(message)


def fmt(value: float) -> str:
    text = f"{float(value):.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def number(value, where: str, lo: float | None = None, hi: float | None = None) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        fail(f"{where} must be a number: {value!r}")
    if lo is not None and value < lo or hi is not None and value > hi:
        fail(f"{where} must be within [{lo}, {hi}]: {value!r}")
    return float(value)


def pair(value, where: str) -> tuple[float, float]:
    if not isinstance(value, list) or len(value) != 2:
        fail(f"{where} must be a two-number list: {value!r}")
    return number(value[0], where + "[0]"), number(value[1], where + "[1]")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest().lower()


def png_size(path: Path) -> tuple[int, int]:
    head = path.read_bytes()[:24]
    if head[:8] != b"\x89PNG\r\n\x1a\n" or head[12:16] != b"IHDR":
        fail(f"{path.name} is not a PNG with a leading IHDR chunk")
    return struct.unpack(">II", head[16:24])


def marker(instance: str, scene_id: str, kind: str) -> str:
    return f"<!-- SCENE:{instance}:{scene_id}:{kind} -->"


def load_json(path: Path, what: str) -> dict:
    if not path.is_file():
        fail(f"{what} is missing: {path.relative_to(ROOT)} (render the people scenes first)")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        fail(f"{what} is not valid JSON: {path.relative_to(ROOT)}: {exc}")
    if not isinstance(data, dict):
        fail(f"{what} must be a JSON object: {path.relative_to(ROOT)}")
    return data


def load_metadata(actor: dict, where: str) -> dict:
    strip, meta_rel = actor["strip"], actor["metadata"]
    if not isinstance(strip, str) or not strip.startswith(STRIP_DIR) or not strip.endswith(".png") or "/" in strip[len(STRIP_DIR):]:
        fail(f"{where}: strip must be {STRIP_DIR}<name>.png: {strip!r}")
    if meta_rel != strip[:-4] + ".json":
        fail(f"{where}: metadata must be the strip's own {STRIP_DIR}<name>.json: {meta_rel!r}")
    strip_path, meta_path = ROOT / strip, ROOT / meta_rel
    if not strip_path.is_file():
        fail(f"{where}: strip PNG is missing: {strip}")
    meta = load_json(meta_path, f"{where}: strip metadata")
    for key in META_KEYS:
        if key not in meta:
            fail(f"{where}: metadata {meta_path.name} lacks '{key}'")
    if meta["file"] != strip_path.name:
        fail(f"{where}: metadata {meta_path.name} describes {meta['file']!r}, not {strip_path.name}")
    for key in ("frame_width", "frame_height", "frame_count", "strip_width", "strip_height", "visible_body_height", "foot_anchor"):
        if isinstance(meta[key], bool) or not isinstance(meta[key], int) or meta[key] <= 0:
            fail(f"{where}: metadata {key} must be a positive integer: {meta[key]!r}")
    fw, fh, n = meta["frame_width"], meta["frame_height"], meta["frame_count"]
    if (meta["strip_width"], meta["strip_height"]) != (fw * n, fh):
        fail(f"{where}: strip_width/strip_height must be {fw * n}x{fh} ({n} frames of {fw}x{fh}): {meta['strip_width']}x{meta['strip_height']}")
    if png_size(strip_path) != (fw * n, fh):
        fail(f"{where}: {strip_path.name} is {png_size(strip_path)}, metadata says {fw * n}x{fh}")
    if sha256(strip_path) != str(meta["sha256"]).lower():
        fail(f"{where}: {strip_path.name} SHA-256 differs from its metadata (re-render or re-pack)")
    if meta["person"] != actor["person"]:
        fail(f"{where}: manifest person {actor['person']!r} differs from metadata person {meta['person']!r}")
    if not (0 < meta["visible_body_height"] <= fh and 0 < meta["foot_anchor"] <= fh):
        fail(f"{where}: visible_body_height/foot_anchor must lie inside the {fh} px frame")
    if not isinstance(meta["frames"], list) or len(meta["frames"]) != n:
        fail(f"{where}: metadata frames must list {n} alpha boxes")
    body = meta["body"]
    if not isinstance(body, dict) or not all(isinstance(body.get(k), int) for k in ("top", "bottom", "left", "right")):
        fail(f"{where}: metadata body must give integer top/bottom/left/right")
    if "seat_anchor" in meta:
        sx, sy = pair(meta["seat_anchor"], f"{where}: metadata seat_anchor")
        if not (0 <= sx <= fw and 0 <= sy <= fh):
            fail(f"{where}: seat_anchor must lie inside the {fw}x{fh} frame")
    return meta


def validate_actor(actor, scene: dict, where: str) -> dict:
    if not isinstance(actor, dict):
        fail(f"{where} must be an object")
    missing, unknown = ACTOR_KEYS - set(actor), set(actor) - ACTOR_KEYS
    if missing or unknown:
        fail(f"{where}: actor keys differ from the contract: missing {sorted(missing)}, unknown {sorted(unknown)}")
    if not isinstance(actor["id"], str) or not SLUG.match(actor["id"]):
        fail(f"{where}: actor id must be a lower-case slug: {actor['id']!r}")
    if actor["person"] not in PERSONS:
        fail(f"{where}: person must be one of {PERSONS}: {actor['person']!r}")
    if actor["anchor"] not in ("feet", "seat"):
        fail(f"{where}: anchor must be 'feet' or 'seat': {actor['anchor']!r}")
    if actor["filter"] not in FILTERS:
        fail(f"{where}: filter must be one of {FILTERS}: {actor['filter']!r}")
    if not isinstance(actor["motion_note"], str) or not actor["motion_note"].strip():
        fail(f"{where}: motion_note must be a non-empty string")
    width, height = scene["width"], scene["height"]
    px, py = pair(actor["position"], f"{where}: position")
    if not (0 <= px <= width and 0 <= py <= height):
        fail(f"{where}: position must lie inside the {width}x{height} source image: {actor['position']}")
    pair(actor["travel"], f"{where}: travel")
    number(actor["body_height"], f"{where}: body_height", 1, height)
    number(actor["move_until"], f"{where}: move_until", 0.05, 1)
    number(actor["duration"], f"{where}: duration", 2, 8.8)
    number(actor["delay"], f"{where}: delay", 0, 1.5)
    if actor["duration"] + actor["delay"] > 8.8 + 0.001:
        fail(f"{where}: duration plus delay must finish within 8.8 seconds")
    number(actor["opacity"], f"{where}: opacity", 0.05, 1)
    shadow = actor["shadow"]
    if shadow is not None:
        if not isinstance(shadow, dict) or set(shadow) != SHADOW_KEYS:
            fail(f"{where}: shadow must be null or an object with exactly rx, ry, opacity, rotate: {shadow!r}")
        number(shadow["rx"], f"{where}: shadow.rx", 0.5, width)
        number(shadow["ry"], f"{where}: shadow.ry", 0.5, height)
        number(shadow["opacity"], f"{where}: shadow.opacity", 0, 1)
        number(shadow["rotate"], f"{where}: shadow.rotate", -360, 360)
    path = actor["visible_path"]
    if path is not None and (not isinstance(path, str) or not path.strip().startswith(("M", "m")) or not PATH_CHARS.match(path)):
        fail(f"{where}: visible_path must be null or an SVG path (M ... Z, numbers only) in source coordinates")
    meta = load_metadata(actor, where)
    if actor["anchor"] == "seat" and "seat_anchor" not in meta:
        fail(f"{where}: anchor 'seat' needs metadata.seat_anchor=[x,y] in {actor['metadata']}")
    return meta


def load_manifest(path: Path = MANIFEST_PATH) -> tuple[dict, dict[str, dict]]:
    """Validate the shared contract strictly and return (manifest, {scene id: {actor id: metadata}})."""
    manifest = load_json(path, "scene manifest")
    if manifest.get("version") != 1:
        fail(f"scenes.json version must be 1: {manifest.get('version')!r}")
    duration = number(manifest.get("duration"), "scenes.json duration", 0.5, 9.0)
    scenes = manifest.get("scenes")
    if not isinstance(scenes, list) or len(scenes) != 9:
        fail("scenes.json must list exactly nine scenes (study-1 .. study-9)")
    metas: dict[str, dict[str, dict]] = {}
    for index, scene in enumerate(scenes, start=1):
        where = f"scene {index}"
        if not isinstance(scene, dict):
            fail(f"{where} must be an object")
        missing, unknown = SCENE_KEYS - set(scene), set(scene) - SCENE_KEYS
        if missing or unknown:
            fail(f"{where}: scene keys differ from the contract: missing {sorted(missing)}, unknown {sorted(unknown)}")
        if scene["id"] != f"study-{index}":
            fail(f"{where}: id must be study-{index} in order: {scene['id']!r}")
        where = scene["id"]
        source = scene["source"]
        if not isinstance(source, str) or not source.startswith("assets/brief/") or "/" in source[len("assets/brief/"):]:
            fail(f"{where}: source must be a file under assets/brief/: {source!r}")
        if not (ROOT / source).is_file():
            fail(f"{where}: source image is missing: {source}")
        for key in ("width", "height"):
            if isinstance(scene[key], bool) or not isinstance(scene[key], int) or scene[key] <= 0:
                fail(f"{where}: {key} must be a positive integer")
        if sha256(ROOT / source) != str(scene["source_sha256"]).lower():
            fail(f"{where}: source_sha256 does not match {source} (the original photo must stay byte-identical)")
        if not isinstance(scene["description"], str) or not scene["description"].strip():
            fail(f"{where}: description must be a non-empty string")
        actors = scene["actors"]
        if not isinstance(actors, list) or not actors:
            fail(f"{where}: every scene needs at least one actor")
        metas[where] = {}
        for actor in actors:
            actor_where = f"{where}/{actor.get('id') if isinstance(actor, dict) else '?'}"
            meta = validate_actor(actor, scene, actor_where)
            if actor["id"] in metas[where]:
                fail(f"{actor_where}: duplicate actor id")
            metas[where][actor["id"]] = meta
            geometry(actor, meta, scene, duration, actor_where)
    return manifest, metas


def geometry(actor: dict, meta: dict, scene: dict, duration: float, where: str = "") -> dict:
    """Viewport placement in source pixels from the actor's own metadata (never a shared body box)."""
    fw, fh, n = meta["frame_width"], meta["frame_height"], meta["frame_count"]
    s = actor["body_height"] / meta["visible_body_height"]
    ax, ay = (fw / 2, meta["foot_anchor"]) if actor["anchor"] == "feet" else tuple(meta["seat_anchor"])
    px, py = actor["position"]
    x, y = px - ax * s, py - ay * s
    body = meta["body"]
    box = (x + body["left"] * s, y + body["top"] * s, x + (body["right"] + 1) * s, y + (body["bottom"] + 1) * s)
    dx, dy = actor["travel"]
    end = (box[0] + dx, box[1] + dy, box[2] + dx, box[3] + dy)
    if where:
        w, h = scene["width"], scene["height"]
        if not (0 <= end[0] and end[2] <= w and 0 <= end[1] and end[3] <= h):
            fail(f"{where}: the body box must finish inside the {w}x{h} image: {tuple(round(v) for v in end)}")
        inside_w = min(box[2], w) - max(box[0], 0)
        inside_h = min(box[3], h) - max(box[1], 0)
        if inside_w <= 0 or inside_h <= 0 or inside_w * inside_h < 0.5 * (box[2] - box[0]) * (box[3] - box[1]):
            fail(f"{where}: at least half of the body box must start inside the {w}x{h} image: {tuple(round(v) for v in box)}")
    return {
        "scale": s, "x": x, "y": y, "width": fw * s, "height": fh * s, "frames": n, "rest": -(n - 1) * fw,
        "shadow_cx": x + meta.get("ground_anchor", [fw / 2, meta["foot_anchor"]])[0] * s, "shadow_cy": y + meta.get("ground_anchor", [fw / 2, meta["foot_anchor"]])[1] * s, "body_start": box, "body_end": end,
        "scene_seconds": actor["duration"], "move_seconds": actor["duration"] * actor["move_until"],
    }


def comment_safe(text: str) -> str:
    return re.sub(r"-{2,}", "-", text.replace("<", "").replace(">", "")).strip()


def render_scene(instance: str, scene: dict, metas: dict[str, dict], duration: float, aspect: str) -> str:
    """One overlay SVG for a scene; `instance` (hero/gallery) prefixes every id so the two copies of study-1 never collide."""
    sid = scene["id"]
    defs, actors = [], []
    for actor in scene["actors"]:
        meta = metas[actor["id"]]
        g = geometry(actor, meta, scene, duration)
        clip_id = f"{instance}-{sid}-{actor['id']}-visible"
        attrs = [f'class="scene-actor"', f'data-actor="{actor["id"]}"', f'data-person="{actor["person"]}"']
        style = (f"--frames:{g['frames']};--rest:{fmt(g['rest'])}px;--tx:{fmt(actor['travel'][0])}px;--ty:{fmt(actor['travel'][1])}px;"
                 f"--scene-seconds:{fmt(g['scene_seconds'])}s;--move-seconds:{fmt(g['move_seconds'])}s;--scene-delay:{fmt(actor['delay'])}s")
        if actor["filter"] != "none":
            style += f";filter:{actor['filter']}"
        attrs.append(f'style="{style}"')
        if actor["opacity"] != 1:
            attrs.append(f'opacity="{fmt(actor["opacity"])}"')
        if actor["visible_path"] is not None:
            defs.append(f'<clipPath id="{clip_id}" clipPathUnits="userSpaceOnUse"><path d="{" ".join(actor["visible_path"].split())}" clip-rule="evenodd"/></clipPath>')
            attrs.append(f'clip-path="url(#{clip_id})"')
        shadow = ""
        if actor["shadow"] is not None:
            sh, cx, cy = actor["shadow"], fmt(g["shadow_cx"]), fmt(g["shadow_cy"])
            shadow = (f'<ellipse class="actor-shadow" cx="{cx}" cy="{cy}" rx="{fmt(sh["rx"])}" ry="{fmt(sh["ry"])}" '
                      f'fill="rgba(30,42,28,{fmt(sh["opacity"])})" transform="rotate({fmt(sh["rotate"])} {cx} {cy})"/>')
        actors.append(
            f'<g {" ".join(attrs)}><g class="actor-move">{shadow}'
            f'<svg class="actor-sprite" x="{fmt(g["x"])}" y="{fmt(g["y"])}" width="{fmt(g["width"])}" height="{fmt(g["height"])}" '
            f'viewBox="0 0 {meta["frame_width"]} {meta["frame_height"]}"><g class="actor-frames">'
            f'<image class="actor-strip" href="{actor["strip"]}" x="0" y="0" width="{meta["strip_width"]}" height="{meta["strip_height"]}"/>'
            f'</g></svg></g></g>')
    people = ", ".join(f"{a['person']} ({Path(a['strip']).name}, {metas[a['id']]['frame_count']} frames, {comment_safe(a['motion_note'])})" for a in scene["actors"])
    head = (f"<!-- {sid} ({instance}): generated by scripts/build_scene_overlays.py from assets/people/scenes.json; do not edit. "
            f"{comment_safe(scene['description'])}. People: {people}. Real Blender renders of licensed Renderpeople scans (Nathan, Carla); "
            f"one {fmt(duration)}s sequence, rest on the last frame at the end position. -->")
    defs_markup = f"<defs>{''.join(defs)}</defs>" if defs else ""
    return (f'{head}<svg class="scene-overlay" data-scene="{sid}" aria-hidden="true" focusable="false" '
            f'viewBox="0 0 {scene["width"]} {scene["height"]}" preserveAspectRatio="{aspect}" xmlns="http://www.w3.org/2000/svg">'
            f'{defs_markup}{"".join(actors)}</svg>')


def render_blocks(manifest: dict, metas: dict[str, dict[str, dict]]) -> list[tuple[str, str, str]]:
    """[(instance, scene id, markup)] for the hero (study-1, slice) and the nine gallery links (meet)."""
    duration = float(manifest["duration"])
    scenes = manifest["scenes"]
    blocks = [("hero", scenes[0]["id"], render_scene("hero", scenes[0], metas[scenes[0]["id"]], duration, "xMidYMid slice"))]
    blocks += [("gallery", s["id"], render_scene("gallery", s, metas[s["id"]], duration, "xMidYMid meet")) for s in scenes]
    return blocks


def find_once(text: str, needle: str, what: str, start: int = 0, end: int | None = None) -> int:
    end = len(text) if end is None else end
    first = text.find(needle, start, end)
    if first < 0:
        fail(f"index.html: cannot find {what}")
    if text.find(needle, first + len(needle), end) >= 0:
        fail(f"index.html: {what} appears more than once")
    return first


def tag_end(text: str, start: int) -> int:
    end = text.find(">", start)
    if end < 0:
        fail("index.html: unterminated tag")
    return end + 1


def matching_svg_end(text: str, start: int) -> int:
    """End offset of the <svg ...>...</svg> element that starts at `start`, counting nested <svg>."""
    depth, pos = 0, start
    while True:
        open_at, close_at = text.find("<svg", pos), text.find("</svg>", pos)
        if close_at < 0:
            fail("index.html: unterminated <svg>")
        if 0 <= open_at < close_at:
            depth, pos = depth + 1, open_at + 4
        else:
            depth, pos = depth - 1, close_at + 6
            if depth == 0:
                return pos


def strip_legacy_hero(text: str, stage_start: int) -> str:
    """First insertion only: remove the hand-written hero walker overlay (comment + <svg class="hero-walkers">)."""
    stage_end = text.find("</div>", stage_start)
    svg_at = text.find(LEGACY_SVG, stage_start, stage_end)
    if svg_at < 0:
        return text
    cut_from = text.rfind(LEGACY_COMMENT, stage_start, svg_at)
    cut_from = svg_at if cut_from < 0 else cut_from
    cut_to = matching_svg_end(text, svg_at)
    line_start = text.rfind("\n", 0, cut_from)
    if text[line_start + 1:cut_from].strip() == "":
        cut_from = line_start
    return text[:cut_from] + text[cut_to:]


def apply_block(text: str, instance: str, sid: str, markup: str) -> str:
    start_marker, end_marker = marker(instance, sid, "START"), marker(instance, sid, "END")
    has_start, has_end = text.count(start_marker), text.count(end_marker)
    if (has_start, has_end) == (1, 1):
        a, b = text.index(start_marker) + len(start_marker), text.index(end_marker)
        if b < a:
            fail(f"index.html: {end_marker} precedes {start_marker}")
        return text[:a] + "\n" + markup + "\n" + text[b:]
    if (has_start, has_end) != (0, 0):
        fail(f"index.html: markers for {instance}/{sid} are damaged (start x{has_start}, end x{has_end})")
    block = f"\n{start_marker}\n{markup}\n{end_marker}"
    if instance == "hero":
        stage = find_once(text, HERO_STAGE, "the hero image stage")
        text = strip_legacy_hero(text, stage)
        img = text.find("<img ", stage, text.find("</div>", stage))
        if img < 0:
            fail("index.html: the hero stage has no <img>")
        at = tag_end(text, img)
        return text[:at] + block + text[at:]
    figure = find_once(text, f'<figure class="study {sid}">', f"figure.study.{sid}")
    figure_end = text.find("</figure>", figure)
    link = text.find('class="study-image"', figure, figure_end)
    img = text.find("<img ", link, figure_end)
    if link < 0 or img < 0:
        fail(f"index.html: figure.study.{sid} lacks a.study-image > img")
    at = tag_end(text, img)
    return text[:at] + block + text[at:]


def apply_all(text: str, blocks: list[tuple[str, str, str]]) -> str:
    for instance, sid, markup in blocks:
        text = apply_block(text, instance, sid, markup)
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate the animated-people scene overlays in index.html from assets/people/scenes.json")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="validate everything, then rewrite only the managed SCENE blocks (inserting them once)")
    mode.add_argument("--check", action="store_true", help="validate everything and compare index.html byte-for-byte with the generated result")
    args = parser.parse_args()
    try:
        manifest, metas = load_manifest()
        blocks = render_blocks(manifest, metas)
        if not INDEX_PATH.is_file():
            fail("index.html is missing")
        current = INDEX_PATH.read_text(encoding="utf-8")
        for needle in ("<!-- FLOOR_PLAN_START -->", "<!-- FLOOR_PLAN_END -->"):
            if current.count(needle) != 1:
                fail(f"index.html must keep exactly one {needle} (the floor plan block is owned by the plan generator)")
        updated = apply_all(current, blocks)
        if apply_all(updated, blocks) != updated:
            fail("generator is not idempotent (internal error)")
    except SceneError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 1
    actors = sum(len(s["actors"]) for s in manifest["scenes"])
    if args.check:
        if updated != current:
            stale = [f"{i}/{s}" for i, s, m in blocks if f"\n{m}\n" not in current]
            print(f"FAIL: index.html scene overlays are stale or missing; run --write. Differing blocks: {stale or 'markup outside the blocks changed'}", file=sys.stderr)
            return 1
        print(f"OK: {len(blocks)} scene overlays ({actors} actors over {len(manifest['scenes'])} scenes) match index.html byte for byte")
        return 0
    if updated == current:
        print(f"Unchanged: {len(blocks)} scene overlays already current")
    else:
        INDEX_PATH.write_text(updated, encoding="utf-8")
        print(f"Wrote {len(blocks)} scene overlays ({actors} actors over {len(manifest['scenes'])} scenes) into index.html")
    return 0


